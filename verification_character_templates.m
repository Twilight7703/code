function output=verification_character_templates(character)
%VERIFICATION_CHARACTER_TEMPLATES 返回验证流程Logo使用的固定5x7字符模板。
% 输入:
%   character - 可选，单个ASCII数字或大写英文字母。
% 输出:
%   output    - 指定字符的7x5 logical矩阵；省略输入时返回模板Map。

charset='0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ';
rows={ ...
    [14 17 19 21 25 17 14], [4 12 4 4 4 4 14], ...
    [14 17 1 2 4 8 31], [30 1 1 14 1 1 30], ...
    [2 6 10 18 31 2 2], [31 16 16 30 1 1 30], ...
    [14 16 16 30 17 17 14], [31 1 2 4 8 8 8], ...
    [14 17 17 14 17 17 14], [14 17 17 15 1 1 14], ...
    [14 17 17 31 17 17 17], [30 17 17 30 17 17 30], ...
    [14 17 16 16 16 17 14], [30 17 17 17 17 17 30], ...
    [31 16 16 30 16 16 31], [31 16 16 30 16 16 16], ...
    [14 17 16 23 17 17 15], [17 17 17 31 17 17 17], ...
    [14 4 4 4 4 4 14], [7 2 2 2 2 18 12], ...
    [17 18 20 24 20 18 17], [16 16 16 16 16 16 31], ...
    [17 27 21 21 17 17 17], [17 25 21 19 17 17 17], ...
    [14 17 17 17 17 17 14], [30 17 17 30 16 16 16], ...
    [14 17 17 17 21 18 13], [30 17 17 30 20 18 17], ...
    [15 16 16 14 1 1 30], [31 4 4 4 4 4 4], ...
    [17 17 17 17 17 17 14], [17 17 17 17 17 10 4], ...
    [17 17 17 21 21 21 10], [17 17 10 4 10 17 17], ...
    [17 17 10 4 4 4 4], [31 1 2 4 8 16 31]};

templates=containers.Map('KeyType','char','ValueType','any');
for index=1:numel(charset)
    values=uint8(rows{index}(:));
    bits=false(7,5);
    for row=1:7
        for column=1:5
            bits(row,column)=bitget(values(row),6-column)~=0;
        end
    end
    templates(charset(index))=bits;
end

if nargin<1
    output=templates;
    return;
end
character=upper(char(character));
if numel(character)~=1 || ~isKey(templates,character)
    error('Verification:UnsupportedLogoCharacter', ...
        'Logo字符必须是0-9或A-Z中的一个字符。');
end
output=templates(character);
end
